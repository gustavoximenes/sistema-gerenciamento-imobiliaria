create or replace function private.horarios_livres(p_imovel_id bigint)
returns table(id bigint, corretor_id bigint, corretor text, inicio timestamptz)
language sql
stable
security definer
set search_path = ''
as $$
    select h.id, h.corretor_id, c.nome::text, h.inicio
    from public.horario h
    join public.corretor c on c.id = h.corretor_id
    where (select auth.uid()) is not null
      and h.inicio > now()
      and h.inicio <= now() + interval '21 days'
      and not exists (
          select 1 from public.visita v
          where v.status <> 'CANCELADA'
            and (v.horario_id = h.id or (v.imovel_id = p_imovel_id and v.inicio = h.inicio))
      )
      and not exists (
          select 1 from public.visita v
          join public.cliente cl on cl.id = v.cliente_id
          where v.status <> 'CANCELADA'
            and cl.auth_id = (select auth.uid()) and v.inicio = h.inicio
      )
    order by h.inicio, c.nome;
$$;
revoke all on function private.horarios_livres(bigint) from public, anon;
grant execute on function private.horarios_livres(bigint) to authenticated;

