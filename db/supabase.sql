create or replace view public.vw_visitas
with (security_invoker = true)
as
select v.id, v.cliente_id, v.imovel_id, h.corretor_id,
       cl.nome as cliente, i.titulo as imovel, c.nome as corretor,
       v.inicio, v.status, v.preco_registrado
from public.visita v
join public.horario h on h.id = v.horario_id
join public.corretor c on c.id = h.corretor_id
join public.cliente cl on cl.id = v.cliente_id
join public.imovel i on i.id = v.imovel_id;

create or replace view public.vw_ranking
with (security_invoker = true)
as select i.titulo, count(*)::bigint as total
from public.visita v join public.imovel i on i.id = v.imovel_id
where v.status = 'REALIZADA' group by i.id, i.titulo;

create or replace view public.vw_baixa_procura
with (security_invoker = true)
as select i.titulo, i.bairro, max(v.inicio) as ultima_visita
from public.imovel i left join public.visita v
  on v.imovel_id = i.id and v.status = 'REALIZADA'
where i.status = 'DISPONIVEL'
group by i.id, i.titulo, i.bairro, i.criado_em
having coalesce(max(v.inicio)::date, i.criado_em) < current_date - 30;

create or replace view public.vw_produtividade
with (security_invoker = true)
as select c.nome,
    count(*) filter (where v.status = 'REALIZADA')::bigint as realizadas,
    count(*) filter (where v.status = 'PENDENTE')::bigint as pendentes,
    count(*) filter (where v.status = 'CANCELADA')::bigint as canceladas
from public.corretor c
left join public.horario h on h.corretor_id = c.id
left join public.visita v on v.horario_id = h.id
group by c.id, c.nome;

create or replace view public.vw_bairros
with (security_invoker = true)
as select i.bairro, count(*)::bigint as total
from public.visita v join public.imovel i on i.id = v.imovel_id
where v.status = 'REALIZADA' group by i.bairro;

create or replace view public.vw_status_visitas
with (security_invoker = true)
as select status, count(*)::bigint as total from public.visita group by status;

create or replace view public.vw_picos_dia
with (security_invoker = true)
as select extract(isodow from inicio)::integer as dia, count(*)::bigint as total
from public.visita where status <> 'CANCELADA' group by extract(isodow from inicio);

create or replace view public.vw_picos_hora
with (security_invoker = true)
as select extract(hour from inicio at time zone 'America/Sao_Paulo')::integer as hora,
          count(*)::bigint as total
from public.visita where status <> 'CANCELADA'
group by extract(hour from inicio at time zone 'America/Sao_Paulo');

create or replace view public.vw_historico_navegacao
with (security_invoker = true)
as select h.id, h.auth_id, h.consultado_em, i.id as imovel_id,
          i.titulo, i.bairro, i.preco, i.status
from public.historico_navegacao h
join public.imovel i on i.id = h.imovel_id;

