create schema if not exists private;
grant usage on schema private to authenticated;

create table if not exists public.cliente (
    id bigint generated by default as identity primary key,
    auth_id uuid unique references auth.users(id) on delete cascade,
    nome varchar(100) not null,
    email varchar(254) not null unique,
    telefone varchar(25),
    criado_em timestamptz not null default now()
);

create table if not exists public.equipe (
    auth_id uuid primary key references auth.users(id) on delete cascade,
    nome varchar(100) not null,
    ativo boolean not null default true
);

create table if not exists public.corretor (
    id bigint generated by default as identity primary key,
    nome varchar(100) not null,
    email varchar(254) not null unique,
    creci varchar(30) not null unique
);

create table if not exists public.proprietario (
    id bigint generated by default as identity primary key,
    nome varchar(100) not null,
    email varchar(254) not null unique,
    telefone varchar(25)
);

create table if not exists public.imovel (
    id bigint generated by default as identity primary key,
    proprietario_id bigint not null references public.proprietario(id),
    titulo varchar(100) not null,
    descricao varchar(1200) not null,
    tipo varchar(30) not null check (tipo in ('CASA','SOBRADO','APARTAMENTO','TERRENO')),
    bairro varchar(70) not null,
    cidade varchar(70) not null default 'Rio do Sul',
    endereco varchar(180) not null,
    quartos smallint not null check (quartos >= 0),
    banheiros smallint not null check (banheiros >= 0),
    vagas smallint not null check (vagas >= 0),
    area_m2 numeric(10,2) not null check (area_m2 > 0),
    preco numeric(14,2) not null check (preco > 0),
    destaque boolean not null default false,
    criado_em date not null default current_date,
    status varchar(12) not null default 'DISPONIVEL'
        check (status in ('DISPONIVEL','RESERVADO','VENDIDO'))
);

create table if not exists public.horario (
    id bigint generated by default as identity primary key,
    corretor_id bigint not null references public.corretor(id),
    inicio timestamptz not null,
    unique (corretor_id, inicio),
    unique (id, inicio)
);

create table if not exists public.visita (
    id bigint generated by default as identity primary key,
    cliente_id bigint not null references public.cliente(id),
    imovel_id bigint not null references public.imovel(id),
    horario_id bigint not null,
    inicio timestamptz not null,
    preco_registrado numeric(14,2) not null check (preco_registrado > 0),
    status varchar(12) not null default 'PENDENTE'
        check (status in ('PENDENTE','REALIZADA','CANCELADA')),
    criado_em timestamptz not null default now(),
    foreign key (horario_id, inicio) references public.horario(id, inicio)
);

create table if not exists public.historico_navegacao (
    id bigint generated by default as identity primary key,
    auth_id uuid not null references auth.users(id) on delete cascade,
    imovel_id bigint not null references public.imovel(id) on delete cascade,
    consultado_em timestamptz not null default now()
);
create index if not exists historico_usuario_data
    on public.historico_navegacao(auth_id, consultado_em desc);

create unique index if not exists visita_horario_ativo
    on public.visita(horario_id) where status <> 'CANCELADA';
create unique index if not exists visita_imovel_inicio_ativo
    on public.visita(imovel_id, inicio) where status <> 'CANCELADA';
create unique index if not exists visita_cliente_inicio_ativo
    on public.visita(cliente_id, inicio) where status <> 'CANCELADA';
create index if not exists visita_imovel_status_inicio
    on public.visita(imovel_id, status, inicio);
create index if not exists visita_horario_inicio on public.visita(horario_id, inicio);
create index if not exists imovel_proprietario on public.imovel(proprietario_id);
create index if not exists historico_imovel on public.historico_navegacao(imovel_id);

create or replace function private.is_equipe()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
    select (select auth.uid()) is not null and exists (
        select 1 from public.equipe e
        where e.auth_id = (select auth.uid()) and e.ativo
    );
$$;
revoke all on function private.is_equipe() from public, anon;
grant execute on function private.is_equipe() to authenticated;

create or replace function private.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
    insert into public.cliente(auth_id, nome, email)
    values (
        new.id,
        left(coalesce(nullif(trim(new.raw_user_meta_data ->> 'nome'), ''), split_part(new.email, '@', 1)), 100),
        lower(new.email)
    )
    on conflict (email) do update
        set auth_id = excluded.auth_id,
            nome = case when public.cliente.auth_id is null then excluded.nome else public.cliente.nome end
        where public.cliente.auth_id is null or public.cliente.auth_id = excluded.auth_id;
    return new;
end;
$$;
revoke all on function private.handle_new_user() from public, anon, authenticated;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute function private.handle_new_user();

