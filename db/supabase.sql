with hs as (
    select h.id, h.inicio, row_number() over(order by h.inicio,h.corretor_id) rn
    from public.horario h
    where h.inicio < now() and extract(hour from h.inicio at time zone 'America/Sao_Paulo') = 9
), cs as (
    select id,row_number() over(order by id) rn from public.cliente
), ims as (
    select id,preco,row_number() over(order by id) rn from public.imovel where status <> 'VENDIDO'
)
insert into public.visita(cliente_id,imovel_id,horario_id,inicio,preco_registrado,status)
select cs.id,ims.id,hs.id,hs.inicio,ims.preco,
       case when hs.rn % 9 = 0 then 'CANCELADA' else 'REALIZADA' end
from hs
join cs on cs.rn=((hs.rn-1)%5)+1
join ims on ims.rn=((hs.rn-1)%5)+1
where not exists(select 1 from public.visita)
order by hs.rn;
