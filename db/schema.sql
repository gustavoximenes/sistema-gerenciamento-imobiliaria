CREATE TABLE IF NOT EXISTS cliente (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL, email VARCHAR(254) NOT NULL UNIQUE, auth_id UUID UNIQUE
);
CREATE TABLE IF NOT EXISTS corretor (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL, email VARCHAR(254) NOT NULL UNIQUE, creci VARCHAR(30) NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS proprietario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL, email VARCHAR(254) NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS imovel (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proprietario_id BIGINT NOT NULL REFERENCES proprietario(id),
    titulo VARCHAR(100) NOT NULL, bairro VARCHAR(70) NOT NULL, endereco VARCHAR(180) NOT NULL,
    preco DECIMAL(14,2) NOT NULL CHECK (preco > 0),
    criado_em DATE DEFAULT CURRENT_DATE NOT NULL,
    status VARCHAR(12) DEFAULT 'DISPONIVEL' NOT NULL CHECK (status IN ('DISPONIVEL','RESERVADO','VENDIDO'))
);
CREATE TABLE IF NOT EXISTS horario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    corretor_id BIGINT NOT NULL REFERENCES corretor(id),
    inicio TIMESTAMP NOT NULL CHECK (EXTRACT(MINUTE FROM inicio) = 0 AND EXTRACT(SECOND FROM inicio) = 0),
    UNIQUE(corretor_id,inicio), UNIQUE(id,inicio)
);
CREATE TABLE IF NOT EXISTS visita (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT NOT NULL REFERENCES cliente(id),
    imovel_id BIGINT NOT NULL REFERENCES imovel(id),
    horario_id BIGINT NOT NULL,
    inicio TIMESTAMP NOT NULL,
    preco_registrado DECIMAL(14,2) NOT NULL CHECK (preco_registrado > 0),
    status VARCHAR(12) DEFAULT 'PENDENTE' NOT NULL CHECK (status IN ('PENDENTE','REALIZADA','CANCELADA')),
    ativo SMALLINT DEFAULT 1,
    CHECK ((status = 'CANCELADA' AND ativo IS NULL) OR
           (status <> 'CANCELADA' AND ativo IS NOT NULL AND ativo = 1)),
    FOREIGN KEY(horario_id,inicio) REFERENCES horario(id,inicio),
    UNIQUE(horario_id,ativo), UNIQUE(imovel_id,inicio,ativo), UNIQUE(cliente_id,inicio,ativo)
);
CREATE INDEX IF NOT EXISTS visita_imovel_status_inicio ON visita(imovel_id,status,inicio);
CREATE TABLE IF NOT EXISTS carga (versao INT PRIMARY KEY);
